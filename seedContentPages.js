// ============================================================
// Run the seed
// ============================================================

async function run() {
  const uri = process.env.MONGODB_URI || process.env.MONGO_URI;
  if (!uri) {
    console.error('MONGODB_URI not found in .env — aborting.');
    process.exit(1);
  }

  await mongoose.connect(uri);
  console.log(`Connected to MongoDB. Seeding ${pages.length} content pages...`);

  for (const page of pages) {
    await ContentPage.findOneAndUpdate(
      { slug: page.slug },
      { $set: page },
      { upsert: true, new: true, setDefaultsOnInsert: true }
    );
    console.log('  ✓ seeded:', page.slug);
  }

  console.log('Done. Seeded', pages.length, 'content pages.');
  await mongoose.disconnect();
  process.exit(0);
}

run().catch((err) => {
  console.error('Seed failed:', err);
  process.exit(1);
});
